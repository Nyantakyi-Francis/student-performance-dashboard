import { test, expect } from '@playwright/test'
import process from 'node:process'

const sandboxKey = 'student-performance-dashboard:v2'
const database = (page) => page.getByRole('region', { name: 'Database view', exact: true })
async function signIn(page, role) {
  await page.getByRole('button', { name: 'Database view', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(`${role}@demo.example`)
  await page.getByLabel('Password', { exact: true }).fill(process.env[role === 'admin' ? 'DEMO_ADMIN_PASSWORD' : 'DEMO_TEACHER_PASSWORD'])
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(database(page).getByText('Database records loaded. This view is read-only.', { exact: true })).toBeVisible()
}

test('sandbox edits and unfinished forms survive mode switching; API data stays separate', async ({ page }, testInfo) => {
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await page.getByPlaceholder('Student name', { exact: true }).fill('Sandbox Student')
  await page.getByRole('spinbutton', { name: 'English', exact: true }).fill('0')
  await page.getByRole('button', { name: 'Add Student', exact: true }).click()
  await expect(page.getByText('Student added.', { exact: true })).toBeVisible()
  await page.getByPlaceholder('Student name', { exact: true }).fill('Unfinished draft')
  const saved = await page.evaluate((key) => localStorage.getItem(key), sandboxKey)
  await signIn(page, 'teacher')
  await expect(database(page).getByRole('button', { name: 'Edit', exact: true })).toHaveCount(0)
  await expect(database(page).getByRole('button', { name: 'Delete', exact: true })).toHaveCount(0)
  await expect(database(page).getByText('Sandbox Student', { exact: true })).toHaveCount(0)
  expect(await page.evaluate((key) => localStorage.getItem(key), sandboxKey)).toBe(saved)
  await page.getByRole('button', { name: 'Browser sandbox', exact: true }).click()
  await expect(page.getByPlaceholder('Student name', { exact: true })).toHaveValue('Unfinished draft')
  await page.reload()
  await expect(page.locator('tbody tr').filter({ hasText: 'Sandbox Student' })).toBeVisible()
  await page.getByRole('button', { name: 'Database view', exact: true }).click()
  await expect(database(page).getByText('Database records loaded. This view is read-only.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(database(page).getByText('Database records loaded. This view is read-only.', { exact: true })).toBeVisible()
  expect(await page.evaluate((key) => localStorage.getItem(key), sandboxKey)).toBe(saved)
  await page.getByRole('heading', { name: 'Student Performance Analytics Dashboard', exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: testInfo.outputPath('database-view.png'), animations: 'disabled' })
  await database(page).getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'School sign-in' })).toBeVisible()
  await expect(database(page).locator('tbody tr')).toHaveCount(0)
  expect(errors).toEqual([])
})

test('administrator assigns and removes teacher access through the real API', async ({ page, browser }) => {
  await page.goto('/')
  await signIn(page, 'admin')
  const access = page.getByRole('region', { name: 'Teacher access management', exact: true })
  await access.getByRole('combobox', { name: 'Teacher', exact: true }).selectOption({ label: 'Demo Teacher' })
  await access.getByRole('combobox', { name: 'Class', exact: true }).selectOption({ label: 'Grade 8 Demo Class' })
  await access.getByRole('combobox', { name: 'Subject', exact: true }).selectOption({ label: 'Science' })
  await access.getByRole('button', { name: 'Assign teacher', exact: true }).click()
  const assignment = access.getByRole('listitem').filter({ hasText: 'Grade 8 Demo Class, Science' })
  await expect(assignment).toBeVisible()
  const teacherContext = await browser.newContext()
  try {
    const teacher = await teacherContext.newPage()
    await teacher.goto('http://127.0.0.1:4178/')
    await signIn(teacher, 'teacher')
    await expect(database(teacher).getByRole('columnheader', { name: 'Science', exact: true })).toBeVisible()
    await expect(teacher.getByRole('region', { name: 'Teacher access management', exact: true })).toHaveCount(0)
    await assignment.getByRole('button', { name: 'Remove assignment', exact: true }).click()
    await expect(assignment).toHaveCount(0)
    await database(teacher).getByRole('button', { name: 'Reload database records', exact: true }).click()
    await expect(database(teacher).getByText('Database records loaded. This view is read-only.', { exact: true })).toBeVisible()
    await expect(database(teacher).getByRole('columnheader', { name: 'Science', exact: true })).toHaveCount(0)
  } finally { await teacherContext.close() }
})

test('loading, error, empty, and retry states never show sandbox records as database data', async ({ page }) => {
  await page.goto('/')
  await page.route('**/api/v1/dashboard-data', (route) => route.fulfill({ status: 503, json: { error: { code: 'UNAVAILABLE', message: 'Test database unavailable.' } } }))
  await page.getByRole('button', { name: 'Database view', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill('teacher@demo.example')
  await page.getByLabel('Password', { exact: true }).fill(process.env.DEMO_TEACHER_PASSWORD)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(database(page).getByRole('alert')).toHaveText('Test database unavailable.')
  await expect(database(page).locator('tbody tr')).toHaveCount(0)
  await page.route('**/api/v1/dashboard-data', (route) => route.fulfill({ json: { data: { students: [], grades: [], subjects: [], terms: [] } } }))
  await database(page).getByRole('button', { name: 'Reload database records', exact: true }).click()
  await expect(database(page).getByRole('status')).toHaveText('No records are available for your school or teaching assignments.')
  await page.unroute('**/api/v1/dashboard-data')
  let release
  const pause = new Promise((resolve) => { release = resolve })
  await page.route('**/api/v1/dashboard-data', async (route) => { await pause; await route.continue() })
  await database(page).getByRole('button', { name: 'Reload database records', exact: true }).click()
  await expect(database(page).getByRole('status')).toHaveText('Loading database records...')
  release()
  await expect(database(page).getByText('Database records loaded. This view is read-only.', { exact: true })).toBeVisible()
})
