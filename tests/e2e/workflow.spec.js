import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import process from 'node:process'
import { Buffer } from 'node:buffer'

async function signIn(page, role) {
  await page.goto('/')
  await page.getByRole('button', { name: 'Database view', exact: true }).click()
  await page.getByLabel('Email', { exact: true }).fill(`${role}@demo.example`)
  const password = role === 'admin' ? process.env.DEMO_ADMIN_PASSWORD : role === 'teacher' ? process.env.DEMO_TEACHER_PASSWORD : process.env[`DEMO_${role.toUpperCase()}_PASSWORD`] || process.env.DEMO_TEACHER_PASSWORD
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByText(new RegExp(`Signed in as Demo ${role === 'admin' ? 'Administrator' : role[0].toUpperCase() + role.slice(1)}`))).toBeVisible()
}
async function audit(page) {
  const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(result.violations.map((v) => ({ id: v.id, nodes: v.nodes.map((n) => n.target) }))).toEqual([])
}

test('teacher saves, imports and publishes results visible only in linked learner reports', async ({ page, browser }, testInfo) => {
  const errors = []
  page.on('pageerror', (e) => errors.push(e.message))
  await signIn(page, 'teacher')
  const workspace = page.getByRole('region', { name: 'Assessment workspace', exact: true })
  await workspace.getByText('Create an assessment', { exact: true }).click()
  const title = `Workflow ${testInfo.project.name} ${Date.now()}`
  await workspace.getByLabel('Assessment title', { exact: true }).fill(title)
  await workspace.getByRole('combobox', { name: 'Assessment class', exact: true }).selectOption({ label: 'Grade 7 Demo Class' })
  await workspace.getByRole('combobox', { name: 'Assessment subject', exact: true }).selectOption({ label: 'English' })
  await workspace.getByRole('combobox', { name: 'Assessment term', exact: true }).selectOption({ index: 1 })
  await workspace.getByLabel('Maximum points', { exact: true }).fill('20')
  await workspace.getByRole('button', { name: 'Create assessment', exact: true }).click()
  await expect(workspace.getByRole('heading', { name: `${title}: draft score entry` })).toBeVisible()
  await workspace.getByLabel('State for ADJHS-2025-001', { exact: true }).selectOption('scored')
  await workspace.getByLabel('Points for ADJHS-2025-001', { exact: true }).fill('0')
  page.once('dialog', (dialog) => dialog.dismiss())
  await page.getByRole('button', { name: 'Browser sandbox', exact: true }).click()
  await expect(workspace.getByLabel('Points for ADJHS-2025-001', { exact: true })).toHaveValue('0')
  await workspace.getByRole('button', { name: 'Save draft scores', exact: true }).click()
  await expect(workspace.getByText('Draft scores saved.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(workspace.getByRole('combobox', { name: 'Open assessment', exact: true })).toBeVisible()
  const option = workspace.getByRole('combobox', { name: 'Open assessment', exact: true }).locator('option').filter({ hasText: title })
  await workspace.getByRole('combobox', { name: 'Open assessment', exact: true }).selectOption(await option.getAttribute('value'))
  await expect(workspace.getByLabel('Points for ADJHS-2025-001', { exact: true })).toHaveValue('0')
  await workspace.getByText('Import scores from CSV', { exact: true }).click()
  const upload = workspace.getByLabel('Score CSV file', { exact: true })
  await upload.setInputFiles({ name: 'invalid.csv', mimeType: 'text/csv', buffer: Buffer.from('studentNumber,status,points,feedback\nADJHS-2025-001,scored,99,Invalid\n') })
  await workspace.getByRole('button', { name: 'Validate import preview' }).click()
  await expect(workspace.getByText(/Row 2: Scored work needs points/)).toBeVisible()
  await expect(workspace.getByRole('button', { name: 'Commit validated import' })).toHaveCount(0)
  await upload.setInputFiles({ name: 'valid.csv', mimeType: 'text/csv', buffer: Buffer.from('studentNumber,status,points,feedback\nADJHS-2025-001,scored,20,Reviewed work\nADJHS-2025-002,missing,,No submission\n') })
  await workspace.getByRole('button', { name: 'Validate import preview' }).click()
  await expect(workspace.getByText('2 rows previewed; 0 errors. No scores have changed.')).toBeVisible()
  await workspace.getByRole('button', { name: 'Commit validated import' }).click()
  await expect(workspace.getByText('Import committed. Draft scores saved.')).toBeVisible()
  await expect(workspace.getByLabel('Points for ADJHS-2025-001', { exact: true })).toHaveValue('20')
  await workspace.getByLabel('Publication or amendment reason').fill('Reviewed synthetic class results')
  await workspace.getByRole('button', { name: 'Publish results', exact: true }).click()
  await expect(workspace.getByText('Results published. Linked students and guardians can view the snapshot.')).toBeVisible()
  await audit(page)
  await page.getByRole('heading', { name: 'Assessment workspace', exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: testInfo.outputPath('teacher-workspace.png') })
  const context = await browser.newContext({ viewport: page.viewportSize() })
  try {
    const learner = await context.newPage()
    await signIn(learner, 'student')
    const report = learner.getByRole('region', { name: 'Published reports', exact: true })
    await expect(report.getByRole('row').filter({ hasText: title })).toContainText('20 / 20')
    await expect(report.getByRole('heading', { name: /Kwame/ })).toHaveCount(0)
    await expect(learner.getByRole('region', { name: 'Assessment workspace', exact: true })).toHaveCount(0)
    await audit(learner)
    await learner.screenshot({ path: testInfo.outputPath('student-report.png'), fullPage: true })
    await learner.getByRole('button', { name: 'Sign out', exact: true }).click()
    await signIn(learner, 'guardian')
    await expect(learner.getByRole('region', { name: 'Published reports', exact: true }).getByRole('row').filter({ hasText: title })).toContainText('Reviewed work')
  } finally { await context.close() }
  expect(errors).toEqual([])
})

test('administrator issues an invitation and a new learner accepts it', async ({ page, browser }, testInfo) => {
  await signIn(page, 'admin')
  const accounts = page.getByRole('region', { name: 'Account management', exact: true })
  await accounts.getByText('Invite an account', { exact: true }).click()
  await accounts.getByLabel('Your current password (for invitations and recovery)', { exact: true }).fill(process.env.DEMO_ADMIN_PASSWORD)
  const email = `browser-${testInfo.project.name}-${Date.now()}@demo.example`
  await accounts.getByLabel('Invitee email', { exact: true }).fill(email)
  await accounts.getByLabel('Invitee name', { exact: true }).fill('Browser Learner')
  await accounts.getByRole('combobox', { name: 'Invitee role', exact: true }).selectOption('student')
  await accounts.getByRole('listbox', { name: 'Linked students (select one for student accounts)', exact: true }).selectOption({ label: 'ADJHS-2025-001: Ama Mensah' })
  await accounts.getByRole('button', { name: 'Create invitation link', exact: true }).click()
  const link = accounts.getByLabel('Single-use account link', { exact: true })
  await expect(link).toBeVisible()
  const url = await link.inputValue()
  const context = await browser.newContext({ viewport: page.viewportSize() })
  try {
    const recipient = await context.newPage()
    await recipient.goto(url)
    await recipient.getByRole('button', { name: 'Database view', exact: true }).click()
    const help = recipient.getByRole('region', { name: 'Account help', exact: true })
    await expect(help.getByLabel('Single-use account token', { exact: true })).not.toHaveValue('')
    await help.getByLabel('New password (12–128 characters)', { exact: true }).fill('Synthetic-browser-learner-password')
    await help.getByRole('button', { name: 'Save account password', exact: true }).click()
    await expect(help.getByText('Password saved. Sign in with your school code and email.')).toBeVisible()
    await recipient.getByLabel('Email', { exact: true }).fill(email)
    await recipient.getByLabel('Password', { exact: true }).fill('Synthetic-browser-learner-password')
    await recipient.getByRole('button', { name: 'Sign in', exact: true }).click()
    await expect(recipient.getByText(/Signed in as Browser Learner/)).toBeVisible()
    await expect(recipient.getByRole('region', { name: 'Account management', exact: true })).toHaveCount(0)
    await audit(recipient)
  } finally { await context.close() }
  await accounts.getByRole('button', { name: 'Hide account link' }).click()
  await audit(page)
})

test('sandbox charts have accessible equivalents and the student dialog contains keyboard focus', async ({ page }) => {
  await page.goto('/')
  await expect(page).toHaveTitle('Student Performance Analytics Dashboard')
  await audit(page)
  await page.getByRole('button', { name: 'View', exact: true }).first().click()
  const dialog = page.getByRole('dialog')
  const close = dialog.getByRole('button', { name: 'Close student details' })
  await expect(close).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(close).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
})
